/// <reference types="vitest/config" />
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { defineConfig, type Plugin } from 'vite';

/**
 * Production Content-Security-Policy. Fonts are self-hosted (bundled from @fontsource), so no
 * third-party origin is needed at all. `worker-src` allows the blob: tracer worker and the
 * same-origin service worker that makes the site work offline.
 */
const CSP = [
  "default-src 'self'",
  "img-src 'self' data: blob:",
  "worker-src 'self' blob:",
  "font-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'none'",
].join('; ');

function cspPlugin(): Plugin {
  return {
    name: 'crest-forge-csp',
    apply: 'build',
    transformIndexHtml(html) {
      return html.replace('<!--csp-->', `<meta http-equiv="Content-Security-Policy" content="${CSP}" />`);
    },
  };
}

function swSource(version: string, assets: string[]): string {
  return `// Generated by vite.config.ts. Precaches the static site so it works offline after first load.
const VERSION = ${JSON.stringify(version)};
const ASSETS = ${JSON.stringify(assets)};
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(VERSION)
      .then((cache) => cache.addAll(ASSETS))
      .then(() => self.skipWaiting()),
  );
});
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // ignoreVary: hosts that answer with "Vary: Origin" would otherwise never match the precache.
  event.respondWith(
    caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req)),
  );
});
`;
}

function serviceWorkerPlugin(): Plugin {
  let outDir = 'dist';
  return {
    name: 'crest-forge-sw',
    apply: 'build',
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir);
    },
    closeBundle() {
      const files: string[] = [];
      const walk = (dir: string): void => {
        for (const name of readdirSync(dir)) {
          const p = join(dir, name);
          if (statSync(p).isDirectory()) walk(p);
          else files.push(relative(outDir, p).replace(/\\/g, '/'));
        }
      };
      walk(outDir);
      const assets = files.filter((f) => f !== 'sw.js' && !f.endsWith('.map')).sort();
      const hash = createHash('sha256');
      for (const f of assets) hash.update(f).update(readFileSync(join(outDir, f)));
      const version = 'crest-forge-' + hash.digest('hex').slice(0, 12);
      writeFileSync(join(outDir, 'sw.js'), swSource(version, ['./', ...assets.map((f) => './' + f)]));
    },
  };
}

export default defineConfig({
  base: './',
  build: { target: 'es2020', sourcemap: false },
  plugins: [cspPlugin(), serviceWorkerPlugin()],
  test: { include: ['tests/**/*.test.ts'], environment: 'node' },
});
